#include "EPD_Hardware.h"
#include "spi.h"

static HAL_StatusTypeDef epdStatus = HAL_OK;
static bool epdInitialized = false;
static bool epdBaseReady = false;
static constexpr uint32_t EPD_BUSY_TIMEOUT_MS = 15000;

HAL_StatusTypeDef EPD_GetStatus(void) { return epdStatus; }

static void EPD_RecordError(HAL_StatusTypeDef status)
{
    if (status != HAL_OK) {
        epdStatus = status;
        epdInitialized = false;
        epdBaseReady = false;
    }
}

void DEV_SPI_WriteByte(uint8_t value)
{
    if (epdStatus == HAL_OK)
        EPD_RecordError(HAL_SPI_Transmit(&hspi1, &value, 1, 1000));
}

void DEV_SPI_Write_nByte(uint8_t *value, uint8_t len)
{
    if (epdStatus == HAL_OK)
        EPD_RecordError(HAL_SPI_Transmit(&hspi1, value, len, 1000));
}

/******************************************************************************
function :	Software reset
parameter:
******************************************************************************/
static void EPD_Reset(void)
{
    epdStatus = HAL_OK;
    epdInitialized = false;
    epdBaseReady = false;
    DEV_Digital_Write(EPD_RST_PIN, 1);
    HAL_Delay(100);
    DEV_Digital_Write(EPD_RST_PIN, 0);
    HAL_Delay(2);
    DEV_Digital_Write(EPD_RST_PIN, 1);
    HAL_Delay(100);
}

/******************************************************************************
function :	Wait until the busy_pin goes LOW
parameter:
******************************************************************************/
void EPD_ReadBusy(void) {
    if (epdStatus != HAL_OK) return;
    const uint32_t start = HAL_GetTick();
    while(DEV_Digital_Read(EPD_BUSY_PIN) == GPIO_PIN_SET) {
        if (static_cast<uint32_t>(HAL_GetTick() - start) >= EPD_BUSY_TIMEOUT_MS) {
            EPD_RecordError(HAL_TIMEOUT);
            return;
        }
        //LOW: idle, HIGH: busy
        HAL_Delay(10);
    }
}


/******************************************************************************
function :	send command
parameter:
     Reg : Command register
******************************************************************************/
static void EPD_SendCommand(uint8_t Reg)
{
    if (epdStatus != HAL_OK) return;
    DEV_Digital_Write(EPD_DC_PIN, 0);
    DEV_Digital_Write(EPD_CS_PIN, 0);
    DEV_SPI_WriteByte(Reg);
    DEV_Digital_Write(EPD_CS_PIN, 1);
}

/******************************************************************************
function :	send data
parameter:
    Data : Write data
******************************************************************************/
static void EPD_SendData(uint8_t Data)
{
    if (epdStatus != HAL_OK) return;
    DEV_Digital_Write(EPD_DC_PIN, 1);
    DEV_Digital_Write(EPD_CS_PIN, 0);
    DEV_SPI_WriteByte(Data);
    DEV_Digital_Write(EPD_CS_PIN, 1);
}


static void EPD_SetWindows(uint32_t Xstart, uint32_t Ystart, uint32_t Xend, uint32_t Yend)
{
    EPD_SendCommand(0x44); // SET_RAM_X_ADDRESS_START_END_POSITION
    EPD_SendData((Xstart>>3) & 0xFF);
    EPD_SendData((Xend>>3) & 0xFF);

    EPD_SendCommand(0x45); // SET_RAM_Y_ADDRESS_START_END_POSITION
    EPD_SendData(Ystart & 0xFF);
    EPD_SendData((Ystart >> 8) & 0xFF);
    EPD_SendData(Yend & 0xFF);
    EPD_SendData((Yend >> 8) & 0xFF);
}

/******************************************************************************
function :	Set Cursor
parameter:
******************************************************************************/
static void EPD_SetCursor(uint32_t Xstart, uint32_t Ystart)
{
    EPD_SendCommand(0x4E); // SET_RAM_X_ADDRESS_COUNTER
    EPD_SendData((Xstart>>3) & 0xFF);

    EPD_SendCommand(0x4F); // SET_RAM_Y_ADDRESS_COUNTER
    EPD_SendData(Ystart & 0xFF);
    EPD_SendData((Ystart >> 8) & 0xFF);
}


/******************************************************************************
function :	Turn On Display
parameter:
******************************************************************************/
static void EPD_TurnOnDisplay(void)
{
    EPD_SendCommand(0x22);
    EPD_SendData(0xF7);
    EPD_SendCommand(0x20);
    EPD_ReadBusy();
}


static void EPD_TurnOnDisplay_Partial(void)
{
    EPD_SendCommand(0x22);
    EPD_SendData(0xFF);
    EPD_SendCommand(0x20);
    EPD_ReadBusy();
}

